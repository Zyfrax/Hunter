// Helper to get formatted date string for relative offsets
const getOffsetDate = (daysOffset: number, hour = 12): string => {
  const d = new Date();
  d.setDate(d.getDate() + daysOffset);
  d.setHours(hour, 0, 0, 0);
  return d.toISOString().slice(0, 16); // YYYY-MM-DDTHH:mm
};

